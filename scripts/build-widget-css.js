#!/usr/bin/env node
// Build step: regenerates worlds/demo-widgets.css from studio/studio.css.
//
// The assistant demos on the homepage are the same widget scripts used across
// the site (studio/*.js, loaded unmodified). Their layout CSS is taken verbatim
// from studio/studio.css so they keep behaving identically; only the colours
// are mapped onto the SparkLab Worlds palette. Runs as part of `npm run build`.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(ROOT, 'studio', 'studio.css'), 'utf8');
const start = src.indexOf('Assistant demo page + chat widget');
const end = src.indexOf('BLOG');
if (start < 0 || end < 0) { console.error('ERROR: studio.css layout changed; widget section markers not found.'); process.exit(1); }
let css = src.slice(src.lastIndexOf('/*', start), src.lastIndexOf('/*', end));

const swaps = [
  [/rgba\(0,\s*229,\s*255,/g, 'rgba(201, 169, 218,'],   // cyan accent tints -> muted lavender
  [/#00e5ff/gi, '#C9A9DA'],
  [/#0a0c1a/gi, '#221C2B'],                              // dark text on accent buttons -> deep plum
  [/rgba\(10,\s*12,\s*26,/g, 'rgba(34, 28, 43,'],
  [/#0c0e24f7/gi, '#2A2236f7'],                          // floating chat panel
  [/#aab3d1/gi, '#CFC5D9'],
  [/#8089a8/gi, '#A79CB4'],
  [/Orbitron,\s*Inter,\s*sans-serif/g, 'inherit'],
];
for (const [a, b] of swaps) css = css.replace(a, b);

const out = `/* GENERATED by scripts/build-widget-css.js from studio/studio.css. Do not edit by hand. */\n${css}`;
fs.writeFileSync(path.join(ROOT, 'worlds', 'demo-widgets.css'), out);
console.log(`build-widget-css: worlds/demo-widgets.css written (${(out.length / 1024).toFixed(1)} KB)`);
